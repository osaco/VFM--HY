#!/usr/bin/env python3
"""Generate the Slint Strings global and Rust binding helper from i18n::KEYS.

Usage:
    python tools/generate_strings.py            # write generated files
    python tools/generate_strings.py --check    # verify checked-in files are current
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
I18N = ROOT / "crates" / "app" / "src" / "i18n.rs"
SLINT_OUT = ROOT / "crates" / "app" / "ui" / "strings.slint"
RUST_OUT = ROOT / "crates" / "app" / "src" / "strings_ui.rs"


def parse_keys() -> list[str]:
    text = I18N.read_text(encoding="utf-8")
    block = text.split("pub const KEYS: &[&str] = &[", 1)[1].split("];", 1)[0]
    return re.findall(r'"([^"]+)"', block)


def prop_name(key: str) -> str:
    return "s_" + re.sub(r"[^a-z0-9]+", "_", key.lower()).strip("_")


def render_slint(keys: list[str]) -> str:
    lines = [
        "// Generated by tools/generate_strings.py from crates/app/src/i18n.rs. Do not edit.",
        "// All user-visible text must read from this global so language changes propagate.",
        "export global Strings {",
    ]
    for key in keys:
        lines.append(f'    in-out property <string> {prop_name(key)}: "{key}";')
    lines.extend(["}", ""])
    return "\n".join(lines)


def render_rust(keys: list[str]) -> str:
    lines = [
        "// Generated by tools/generate_strings.py from crates/app/src/i18n.rs. Do not edit.",
        "//! Generated bridge between the i18n catalog and Slint string properties.",
        "",
        "use slint::ComponentHandle;",
        "use vfm_core::Language;",
        "",
        "use crate::{i18n, AppWindow, GalleryWindow, LibraryWindow, OnboardingWindow, CustomizeWindow, OpenMediaWindow, PipWindow, PlayerWindow, SettingsWindow, Strings};",
        "",
    ]

    def apply_fn(fn_name: str, ui_type: str) -> None:
        lines.extend(
            [
                f"#[allow(dead_code)]",
                f"pub fn {fn_name}(ui: &{ui_type}, language: Language) {{",
                "    let strings = ui.global::<Strings>();",
            ]
        )
        for key in keys:
            lines.append(
                f'    strings.set_{prop_name(key)}(i18n::translate(language, "{key}").into());'
            )
        lines.extend(["}", ""])

    apply_fn("apply_app", "AppWindow")
    apply_fn("apply_gallery", "GalleryWindow")
    apply_fn("apply_player", "PlayerWindow")
    apply_fn("apply_pip", "PipWindow")
    apply_fn("apply_library", "LibraryWindow")
    apply_fn("apply_settings", "SettingsWindow")
    apply_fn("apply_onboarding", "OnboardingWindow")
    apply_fn("apply_open", "OpenMediaWindow")
    apply_fn("apply_customize", "CustomizeWindow")
    return "\n".join(lines)


def format_rust(content: str) -> str:
    temp = RUST_OUT.with_name("strings_ui.generated.rs")
    temp.write_text(content, encoding="utf-8")
    try:
        subprocess.run(["rustfmt", "--edition", "2021", str(temp)], check=True)
        return temp.read_text(encoding="utf-8")
    finally:
        temp.unlink(missing_ok=True)


def main() -> None:
    keys = parse_keys()
    outputs = {
        SLINT_OUT: render_slint(keys),
        RUST_OUT: format_rust(render_rust(keys)),
    }
    if "--check" in sys.argv:
        for path, expected in outputs.items():
            if not path.exists() or path.read_text(encoding="utf-8") != expected:
                raise SystemExit(f"{path.relative_to(ROOT)} is stale; run python tools/generate_strings.py")
        print("strings.slint and strings_ui.rs are current")
        return
    for path, content in outputs.items():
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
