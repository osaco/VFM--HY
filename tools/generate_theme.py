#!/usr/bin/env python3
"""Generate the Slint theme module from design/tokens.md.

Usage:
    python tools/generate_theme.py            # write crates/app/ui/theme.slint
    python tools/generate_theme.py --check    # verify the checked-in file is current
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / "design" / "tokens.md"
OUTPUT = ROOT / "crates" / "app" / "ui" / "theme.slint"


def slint_name(token: str) -> str:
    return token.strip().replace(".", "-")


METRIC_ORDER = [
    "control-height-sm", "control-height-md", "control-height-lg",
    "icon-size-sm", "icon-size-md", "icon-size-lg",
    "border-width", "focus-width", "track-height", "seek-height",
    "seek-fill-height", "seek-thumb-width",
    "player-topbar-height", "player-bottombar-height", "player-icon-button",
    "player-play-width", "player-play-height",
    "volume-cone-width", "volume-cone-height",
    "menu-width", "menu-row-height", "dialog-width",
    "tooltip-width", "tab-min-width", "scrollbar-width",
    "thumbnail-width", "thumbnail-height",
]


def parse_tokens() -> dict[str, dict[str, str]]:
    text = TOKENS.read_text(encoding="utf-8")

    def table_between(start: str, end: str) -> dict[str, str]:
        chunk = text.split(start, 1)[1].split(end, 1)[0]
        found: dict[str, str] = {}
        for line in chunk.splitlines():
            match = re.match(r"\|\s*`([^`]+)`\s*\|\s*`(#[0-9A-Fa-f]{6,8})`\s*\|", line)
            if match:
                found[match.group(1)] = match.group(2)
        return found

    dark = table_between("## Color", "### Light theme palette")
    light = table_between("### Light theme palette", "## Typography")

    def first(pattern: str) -> str:
        match = re.search(pattern, text)
        if not match:
            raise SystemExit(f"token pattern not found: {pattern}")
        return match.group(1)

    scale = [int(n) for n in first(r"Scale:\s*`([^`]+)`\s*px").split("/")]
    spacing = [int(n) for n in first(r"Base grid \d+px:\s*`([^`]+)`").split(",")]
    radii = [int(n) for n in re.findall(r"`(\d+)`", text.split("## Radii", 1)[1].split("### Derived component metrics", 1)[0])]
    line_height = float(first(r"line-height\s*`([\d.]+)`"))

    metrics_chunk = text.split("### Derived component metrics", 1)[1].split("## Elevation", 1)[0]
    metrics: dict[str, str] = {}
    for line in metrics_chunk.splitlines():
        match = re.match(r"\|\s*`([^`]+)`\s*\|\s*`(\d+)px`\s*\|", line)
        if match:
            metrics[slint_name(match.group(1))] = f"{match.group(2)}px"

    if len(scale) != 8 or len(spacing) != 7 or len(radii) != 5:
        raise SystemExit("unexpected token counts in tokens.md")
    if set(metrics) != set(METRIC_ORDER):
        missing = sorted(set(METRIC_ORDER) - set(metrics))
        extra = sorted(set(metrics) - set(METRIC_ORDER))
        raise SystemExit(f"unexpected component metrics: missing={missing} extra={extra}")

    return {
        "dark": dark,
        "light": light,
        "scale": [str(n) for n in scale],
        "spacing": [str(n) for n in spacing],
        "radii": [str(n) for n in radii],
        "line_height": str(line_height),
        "metrics": metrics,
    }


def color_pair(tokens: dict[str, dict[str, str]], name: str) -> str:
    dark = tokens["dark"][name]
    light = tokens["light"].get(name, dark)
    return f"mode == 1 ? {light} : {dark}"


def render(tokens: dict[str, dict[str, str]]) -> str:
    lines = [
        "// Generated by tools/generate_theme.py from design/tokens.md. Do not edit by hand.",
        "// mode: 0 = dark (Figma source), 1 = light. `accent` is runtime-changeable.",
        "export global Theme {",
        "    in-out property <int> mode: 0;",
        f"    in-out property <color> accent: {tokens['dark']['accent.default']};",
        "    in-out property <bool> rtl: false;",
        "",
        "    // Color",
    ]
    for name, dark in tokens["dark"].items():
        if name in {"accent.default", "focus.ring"}:
            continue
        if name == "text.on-accent":
            # Runtime-computed from the active accent (see `apply_accent` in main.rs):
            # a bright accent keeps the design's near-black ink, a saturated one flips to white.
            lines.append("    in-out property <color> text-on-accent: #0B0B0B;")
            continue
        prop = slint_name(name)
        if name.startswith("accent."):
            continue
        lines.append(f"    out property <color> {prop}: {color_pair(tokens, name)};")
    lines.extend(
        [
            # Slint's Color.mix(other, factor) weights `self` by factor, so the factor is the
            # accent share and `other` is the amount blended in.
            "    out property <color> accent-hover: accent.mix(#FFFFFF, 0.88);",
            "    out property <color> accent-pressed: accent.mix(#000000, 0.88);",
            "    out property <color> accent-soft: accent.mix(bg-surface, 0.14);",
            "    out property <color> focus-ring: accent;",
            "",
            "    // Typography",
            '    out property <string> font-latin: "Inter";',
            '    out property <string> font-arabic: "Noto Sans Arabic";',
            "    out property <string> font: rtl ? font-arabic : font-latin;",
        ]
    )
    for i, size in enumerate(tokens["scale"]):
        lines.append(f"    out property <length> text-{i + 1}: {size}px;")
    lines.append(f"    out property <float> line-height: {tokens['line_height']};")
    lines.extend(["", "    // Spacing (4px grid)"])
    for i, value in enumerate(tokens["spacing"], start=1):
        lines.append(f"    out property <length> space-{i}: {value}px;")
    lines.extend(
        [
            "",
            "    // Radii",
            f"    out property <length> radius-sm: {tokens['radii'][0]}px;",
            f"    out property <length> radius-md: {tokens['radii'][1]}px;",
            f"    out property <length> radius-lg: {tokens['radii'][2]}px;",
            f"    out property <length> radius-xl: {tokens['radii'][3]}px;",
            f"    out property <length> radius-pill: {tokens['radii'][4]}px;",
            "",
            "    // Component metrics",
        ]
    )
    for name in METRIC_ORDER:
        lines.append(f"    out property <length> {name}: {tokens['metrics'][name]};")
    lines.extend(
        [
            "",
            "    // Elevation",
            "    out property <color> shadow-color: #00000066;",
            "    out property <length> shadow-e1-blur: 2px;",
            "    out property <length> shadow-e1-y: 1px;",
            "    out property <length> shadow-e2-blur: 12px;",
            "    out property <length> shadow-e2-y: 4px;",
            "    out property <length> shadow-e3-blur: 32px;",
            "    out property <length> shadow-e3-y: 12px;",
            "",
            "    // Motion",
            "    out property <duration> motion-fast: 120ms;",
            "    out property <duration> motion-base: 200ms;",
            "    out property <duration> motion-slow: 320ms;",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> None:
    generated = render(parse_tokens())
    if "--check" in sys.argv:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != generated:
            raise SystemExit(f"{OUTPUT} is stale; run python tools/generate_theme.py")
        print("theme.slint is current")
        return
    OUTPUT.write_text(generated, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
