fn map(
    entries: &'static [(&'static str, &'static str)],
) -> &'static HashMap<&'static str, &'static str> {
    static EN_MAP: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
    static AR_MAP: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
    let cell = if std::ptr::eq(entries, EN) {
        &EN_MAP
    } else {
        &AR_MAP
    };
    cell.get_or_init(|| entries.iter().copied().collect())
}

/// Translate a key, falling back to the key itself when a catalog is incomplete.
pub fn translate(language: Language, key: &str) -> &str {
    let catalog = map(match language {
        Language::En => EN,
        Language::Ar => AR,
    });
    catalog.get(key).copied().unwrap_or(key)
}

pub fn is_rtl(language: Language) -> bool {
    language == Language::Ar
}

/// Current UI language, kept globally so helpers that build their own labels
/// (preset scope, slider read-outs) can localise without every call site
/// having to thread the language through.
static UI_LANGUAGE: AtomicU8 = AtomicU8::new(0);

pub fn set_ui_language(language: Language) {
    UI_LANGUAGE.store(
        if language == Language::Ar { 1 } else { 0 },
        Ordering::Relaxed,
    );
}

pub fn ui_language() -> Language {
    if UI_LANGUAGE.load(Ordering::Relaxed) == 1 {
        Language::Ar
    } else {
        Language::En
    }
}

