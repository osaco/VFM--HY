    fn every_key_has_both_languages() {
        for key in KEYS {
            assert_ne!(translate(Language::En, key), *key, "missing EN key {key}");
            assert_ne!(translate(Language::Ar, key), *key, "missing AR key {key}");
        }
    }

    #[test]
    fn arabic_is_rtl() {
        assert!(!is_rtl(Language::En));
        assert!(is_rtl(Language::Ar));
    }
